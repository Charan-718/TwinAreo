const POLICY_LABEL: Record<string, string> = {
  point_estimate: 'Point estimate',
  split_lower_90: 'Split conformal, 90% lower bound',
  cqr_adapted_lower_90: 'Adapted CQR, 90% lower bound',
  agent: 'Agent (95% bound under discrepancy)',
};

function findings(e: Experiments): string[] {
  const ab = e.fd004.ablation;
  const a0 = ab[0];
  const a1 = ab[1];
  const a2 = ab.find((r) => r.id === 'A2')!;
  const a3 = ab.find((r) => r.id === 'A3')!;
  const pol = e.fd004.decisions.policies;
  const tr = e.transfer.variants;
  const out: string[] = [];
  out.push(
    a1.rmse <= a0.rmse
      ? `Regime-normalized twin features improve point accuracy over raw sensors (RMSE ${a1.rmse} vs ${a0.rmse}).`
      : `Regime-normalized twin features do not improve point accuracy over raw sensors for the gradient-boosted model (RMSE ${a1.rmse} vs ${a0.rmse}); the tree ensemble learns regime effects from the settings itself. Their value is in the anomaly, fault-mode and drift components, which need regime-free signals.`,
  );
  out.push(`Self-calibration moves 90% interval coverage from ${fmt.pct(a2.coverage_90)} to ${fmt.pct(a3.coverage_90)} using unlabeled fleet predictions, at a width of ${fmt.num(a3.width_90, 1)} cycles.`);
  out.push(`Deciding on the point estimate misses ${pol.point_estimate.missed_removals} of ${pol.point_estimate.oracle_removals} engines that needed removal; deciding on the interval's lower bound misses ${pol.cqr_adapted_lower_90.missed_removals}, at the cost of ${pol.cqr_adapted_lower_90.unnecessary_removals} unnecessary removals.`);
  if (tr.length >= 3) {
    out.push(`Under domain shift (FD002 to FD004) coverage falls to ${fmt.pct(tr[0].empirical_coverage_pct_90)}. Label-free reweighting does not repair a new fault mode (${fmt.pct(tr[1].empirical_coverage_pct_90)}); refitting the corrections on 25 new failures does (${fmt.pct(tr[2].empirical_coverage_pct_90)}).`);
  }
  out.push(`The discrepancy detector flags ${fmt.pct(e.transfer.drift_detection.in_domain_flag_rate_pct)} of in-domain engines and ${fmt.pct(e.transfer.drift_detection.shifted_flag_rate_pct)} of shifted ones.`);
  out.push(`The what-if surrogate passes its consistency checks, but C-MAPSS cannot validate its effect sizes; it is presented as assumption-based.`);
  return out;
}

